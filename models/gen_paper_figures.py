"""
Generate all CSV-based paper figures at publication quality (300 DPI).

Inputs (must already exist):
  results/table1_full.csv         (mean + std across MAIN_SEEDS, from final_comparison.py)
  results/agg/significance_tests.csv  (seed-level tests, from aggregate_multiseed.py)

Outputs:
  fig22_main_heatmap.png
  fig23_method_bars.png  (now with seed-std error bars)
  fig24_improvement.png

(fig16_variable_contribution_heatmap.png is generated by contribution_analysis.py,
not here -- see that script for why.)
"""
import os
import sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches

sys.path.insert(0, os.path.dirname(__file__))
import paper_style
from tcnae_utils import AGG_DIR, MAIN_SEEDS, OUTDIR

paper_style.apply()

HARD_FAULTS = {3, 9, 15, 16, 17, 18, 19, 20}
EASY_FAULTS = {1, 2, 4, 5, 6, 7, 8, 12, 13, 14}
MED_FAULTS  = {10, 11}

FAULT_NAMES = {
    1:"A/C feed ratio", 2:"B comp step", 3:"D feed temp step",
    4:"Reactor CW temp", 5:"Condenser CW temp", 6:"A feed loss",
    7:"C pressure loss", 8:"A,B,C feed comp", 9:"D feed temp random",
    10:"C feed temp random", 11:"Reactor CW random", 12:"Condenser CW random",
    13:"Reaction kinetics", 14:"Reactor CW valve", 15:"Cond. CW valve",
    16:"Unknown-16", 17:"Unknown-17", 18:"Unknown-18",
    19:"Unknown-19", 20:"Unknown-20"
}

METHOD_ORDER = [
    'PCA-Q(n=7)', 'PCA-Comb(n=29)', 'DenseAE-CP', 'TCNAE-MSE-CP', 'TCNAE-MaxPV-CP',
    'TCNAE-OR(MSE+MaxPV)-CP', 'NormMaxPV-solo', 'OR(MSE+NormMaxPV)',
    'OR(MSE+PVBC)', 'TCNAE-Mahal-CP',
]
METHOD_LABELS = {
    'PCA-Q(n=7)':             'PCA-Q (n=7)',
    'PCA-Comb(n=29)':         'PCA-Comb (n=29)',
    'DenseAE-CP':             'Dense AE+CP',
    'TCNAE-MSE-CP':           'TCN-AE+CP (MSE)',
    'TCNAE-MaxPV-CP':         'TCN-AE+CP (MaxPV)',
    'TCNAE-OR(MSE+MaxPV)-CP': 'TCN-AE+CP (OR: MSE+MaxPV)',
    'NormMaxPV-solo':         'TCN-AE+CP (NormMaxPV)',
    'OR(MSE+NormMaxPV)':      'TCN-AE+CP (OR: MSE+NormMaxPV)',
    'OR(MSE+PVBC)':           'TCN-AE+CP (OR: MSE+PVBC)',
    'TCNAE-Mahal-CP':         'TCN-AE+CP (Mahal)',
}
METHOD_COLORS = {
    'PCA-Q(n=7)':             '#5C85D6',
    'PCA-Comb(n=29)':         '#3A7EBD',
    'DenseAE-CP':             '#FFA500',
    'TCNAE-MSE-CP':           '#4CAF50',
    'TCNAE-MaxPV-CP':         '#9C27B0',
    'TCNAE-OR(MSE+MaxPV)-CP': '#E85D4A',
    'NormMaxPV-solo':         '#D4380D',
    'OR(MSE+NormMaxPV)':      '#FF8C00',
    'OR(MSE+PVBC)':           '#FF6B35',
    'TCNAE-Mahal-CP':         '#888888',
}

easy_sorted    = sorted(EASY_FAULTS)
med_sorted     = sorted(MED_FAULTS)
hard_sorted    = sorted(HARD_FAULTS)
faults_ordered = easy_sorted + med_sorted + hard_sorted

# ── Load results table (mean + std across MAIN_SEEDS) ─────────────────────────
print("Loading table1_full.csv ...")
table = pd.read_csv(OUTDIR / "table1_full.csv")
rows  = []
for _, r in table.iterrows():
    fid = int(r['fault_id'])
    for m in METHOD_ORDER:
        col = f'FDR_{m}'
        if col in r and not pd.isna(r[col]):
            rows.append({'fault_id': fid, 'method': m, 'FDR': r[col] / 100.0,
                          'FDR_std': r.get(f'FDR_std_{m}', 0.0) / 100.0})
all_df = pd.DataFrame(rows)
fault_ids     = sorted(all_df['fault_id'].unique())
methods_avail = [m for m in METHOD_ORDER if not all_df[all_df['method'] == m].empty]

# Seed-level significance tests were already computed by aggregate_multiseed.py
# (naive per-run Wilcoxon on a single seed is not a valid robustness claim).
sig_path = AGG_DIR / "significance_tests.csv"
sig_df = pd.read_csv(sig_path) if sig_path.exists() else pd.DataFrame()


def lookup_p(comparison_substring: str) -> float:
    if sig_df.empty:
        return float('nan')
    hit = sig_df[sig_df['comparison'].str.contains(comparison_substring, regex=False)]
    if hit.empty:
        return float('nan')
    p = hit.iloc[0].get('p_ttest_1samp')
    if pd.isna(p):
        p = hit.iloc[0].get('p_ttest_rel')
    return float(p)


def fmt_p(p: float) -> str:
    """A p-value is never exactly zero; report a floor instead of '0.0000'."""
    if np.isnan(p):
        return "n/a"
    return "p<0.0001" if p < 0.0001 else f"p={p:.4f}"


p_nc = lookup_p('NormMaxPV-solo vs PCA-Comb(n=29)')
p_no = lookup_p('NormMaxPV-solo vs TCN-OR(MSE+MaxPV)')
print(f"  [seed-level t-test, n={len(MAIN_SEEDS)}] NormMaxPV vs PCA-Comb: {fmt_p(p_nc)}   vs TCN-OR: {fmt_p(p_no)}")

# Series needed by fig24 (per-fault improvement plot below)
comb_fdrs = all_df[all_df['method'] == 'PCA-Comb(n=29)'].set_index('fault_id')['FDR']
norm_fdrs = all_df[all_df['method'] == 'NormMaxPV-solo'].set_index('fault_id')['FDR']
shared    = sorted(set(norm_fdrs.index) & set(comb_fdrs.index))

# ── fig22: FDR heatmap, all methods × all faults ─────────────────────────────────
print("\nfig22: FDR heatmap ...")
heat_data = np.full((len(methods_avail), len(faults_ordered)), np.nan)
for i, meth in enumerate(methods_avail):
    sub = all_df[all_df['method'] == meth].set_index('fault_id')
    for j, fid in enumerate(faults_ordered):
        if fid in sub.index:
            heat_data[i, j] = sub.loc[fid, 'FDR'] * 100

_, ax = plt.subplots(figsize=(paper_style.W2 + 2.5, 5.0))
im   = ax.imshow(heat_data, cmap='RdYlGn', vmin=0, vmax=100, aspect='auto')
cbar = plt.colorbar(im, ax=ax, label='FDR (%)', shrink=0.85, pad=0.02)
cbar.ax.tick_params(labelsize=7)

ax.set_xticks(range(len(faults_ordered)))
ax.set_xticklabels([f"F{f}" for f in faults_ordered], fontsize=7.5)
ax.set_yticks(range(len(methods_avail)))
ax.set_yticklabels([METHOD_LABELS.get(m, m) for m in methods_avail], fontsize=8)

for i in range(len(methods_avail)):
    for j in range(len(faults_ordered)):
        v = heat_data[i, j]
        if not np.isnan(v):
            txt_col = 'white' if (v < 25 or v > 85) else 'black'
            ax.text(j, i, f'{v:.0f}', ha='center', va='center',
                    fontsize=6.5, color=txt_col, fontweight='bold')

n_easy = len(easy_sorted)
n_med = len(med_sorted)
ax.axvline(n_easy - 0.5,          color='navy',    lw=1.5, linestyle='--', alpha=0.7)
ax.axvline(n_easy + n_med - 0.5,  color='darkred', lw=1.5, linestyle='--', alpha=0.7)
ax.text(n_easy / 2 - 0.5,                              -0.8,
        'Easy',  ha='center', fontsize=8, color='navy',    style='italic')
ax.text(n_easy + n_med / 2 - 0.5,                      -0.8,
        'Med.',  ha='center', fontsize=8, color='#8B6914', style='italic')
ax.text(n_easy + n_med + len(hard_sorted) / 2 - 0.5,   -0.8,
        'Hard',  ha='center', fontsize=8, color='darkred', style='italic')

ax.set_xlabel('Fault ID', fontsize=9)
ax.set_title('Fault Detection Rate (%) — All Methods × All Faults', fontsize=10, pad=12)
plt.savefig(f"{OUTDIR}/fig22_main_heatmap.png")
plt.close()
print("  Saved fig22_main_heatmap.png")

# ── fig23: Mean FDR bar chart by category ────────────────────────────────────────
print("fig23: Method comparison bars ...")
categories = {
    'Easy\n(F1,2,4–8,12–14)': EASY_FAULTS,
    'Medium\n(F10,11)':         MED_FAULTS,
    'Hard\n(F3,9,15–20)':      HARD_FAULTS,
    'All\n(F1–20)':            set(fault_ids),
}

_, ax = plt.subplots(figsize=(paper_style.W2 + 2.0, 4.8))
n_cats    = len(categories)
n_methods = len(methods_avail)
x = np.arange(n_cats)
w = 0.80 / n_methods

for mi, meth in enumerate(methods_avail):
    sub = all_df[all_df['method'] == meth].set_index('fault_id')
    heights, errs = [], []
    for fset in categories.values():
        fs = [f for f in fset if f in sub.index]
        if fs:
            heights.append(sub.loc[fs, 'FDR'].mean() * 100)
            # propagate per-fault seed-std into a category-level SEM,
            # assuming faults are independent draws
            errs.append(float(np.sqrt((sub.loc[fs, 'FDR_std'] ** 2).mean()) / np.sqrt(len(fs)) * 100))
        else:
            heights.append(0)
            errs.append(0)
    offsets = x + (mi - (n_methods - 1) / 2) * w
    bars = ax.bar(offsets, heights, w * 0.92, yerr=errs, capsize=2,
                  label=METHOD_LABELS.get(meth, meth),
                  color=METHOD_COLORS.get(meth, '#aaaaaa'), alpha=0.88)
    for bar, h in zip(bars, heights):
        ax.text(bar.get_x() + bar.get_width() / 2, h + 0.5,
                f'{h:.0f}', ha='center', va='bottom', fontsize=5.5, rotation=90)

ax.set_xticks(x)
ax.set_xticklabels(list(categories.keys()), fontsize=9)
ax.set_ylabel('Mean FDR (%)', fontsize=9)
ax.set_ylim(0, 128)
ax.set_title(
    'Mean Fault Detection Rate by Category (error bars: std across 5 seeds)\n'
    f'Seed-level t-test (NormMaxPV > PCA-Comb): {fmt_p(p_nc)}   '
    f'(NormMaxPV > TCN-OR): {fmt_p(p_no)}',
    fontsize=9
)
ax.legend(fontsize=7.5, loc='upper left', ncol=2, framealpha=0.9, edgecolor='0.7')
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
ax.grid(axis='y', alpha=0.35)
plt.savefig(f"{OUTDIR}/fig23_method_bars.png")
plt.close()
print("  Saved fig23_method_bars.png")

# ── fig24: Per-fault improvement NormMaxPV vs PCA-Comb ───────────────────────────
print("fig24: Per-fault improvement ...")
ordered24  = [f for f in faults_ordered if f in set(shared)]
delta      = [(norm_fdrs[f] - comb_fdrs[f]) * 100 for f in ordered24]
bar_colors = ['#D4380D' if d >= 0 else '#3A7EBD' for d in delta]

_, ax = plt.subplots(figsize=(paper_style.W2 + 2.0, 3.2))
bars = ax.bar(range(len(ordered24)), delta, color=bar_colors,
              edgecolor='white', linewidth=0.4)
ax.axhline(0, color='black', lw=0.8)

n_easy24 = sum(1 for f in ordered24 if f in EASY_FAULTS)
n_med24  = sum(1 for f in ordered24 if f in MED_FAULTS)
ax.axvline(n_easy24 - 0.5,          color='navy',    lw=1.2, linestyle='--', alpha=0.6)
ax.axvline(n_easy24 + n_med24 - 0.5, color='darkred', lw=1.2, linestyle='--', alpha=0.6)

y_min = min(delta) - 8
ax.text(n_easy24 / 2 - 0.5,                              y_min,
        'Easy', ha='center', fontsize=8, color='navy',    style='italic')
ax.text(n_easy24 + n_med24 / 2 - 0.5,                    y_min,
        'Med.', ha='center', fontsize=8, color='#8B6914', style='italic')
ax.text(n_easy24 + n_med24 + len(hard_sorted) / 2 - 0.5, y_min,
        'Hard', ha='center', fontsize=8, color='darkred', style='italic')

ax.set_xticks(range(len(ordered24)))
ax.set_xticklabels([f"F{f}" for f in ordered24], fontsize=8)
ax.set_ylabel('ΔFDR (percentage points)', fontsize=9)
ax.set_title(
    f'Per-Fault Improvement: TCN-AE+CP (NormMaxPV) vs PCA-Comb (n=29)'
    f'   [Wilcoxon p={p_nc:.4f}]',
    fontsize=9
)
for bar, d in zip(bars, delta):
    ax.text(bar.get_x() + bar.get_width() / 2,
            d + (1.5 if d >= 0 else -4.0),
            f'{d:+.0f}', ha='center', va='bottom', fontsize=6.5, rotation=90)
pos_patch = mpatches.Patch(color='#D4380D', label='NormMaxPV better')
neg_patch = mpatches.Patch(color='#3A7EBD', label='PCA-Comb better')
ax.legend(handles=[pos_patch, neg_patch], fontsize=8, framealpha=0.9, edgecolor='0.7')
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
ax.grid(axis='y', alpha=0.35)
plt.savefig(f"{OUTDIR}/fig24_improvement.png")
plt.close()
print("  Saved fig24_improvement.png")

# fig16 (variable contribution heatmap) is owned by contribution_analysis.py,
# not this script. It uses a sequential Reds/vmin=0 colormap there because
# c_j(X) (Eq. 25, normalized by calibration std -- round-2 review, point 6b)
# is non-negative by construction; an earlier version of this file duplicated
# the plot with a diverging RdBu_r/center=0 colormap left over from a prior
# script version whose (unnormalized) contribution definition really could go
# negative. Two scripts writing the same output file let the stale, wrong-for-
# non-negative-data version silently clobber the correct one on every rerun of
# this script -- removed rather than fixed in place, since a figure should
# have exactly one generator.

print("\nDone. All CSV-based paper figures saved at 300 DPI.")
